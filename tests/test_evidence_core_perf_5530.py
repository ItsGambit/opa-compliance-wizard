"""Performance of the evidence core on a synthetic archive (acceptance criterion 4): a 12-month period over
1,000,000 events streamed to /dev/null must finish within 10 minutes and 512 MB of resident memory.

Skipped unless OPA_PERF=1 (CI skips it: `-m "not perf"` also works). The archive is generated by a subprocess with
bulk inserts (the real manifest writer seals one manifest per day, so the chain is real) and the measurement runs in
a second, fresh subprocess so the peak RSS is the reader's alone.

    OPA_PERF=1 .venv/bin/python -m pytest -q -s tests/test_evidence_core_perf_5530.py
    OPA_PERF_EVENTS=200000 ...      a smaller archive (the limits are only asserted at 1,000,000)
    OPA_PERF_MANIFESTS=1 ...        one manifest holding every event (a first backfill) instead of one per day
    OPA_PERF_DB=/path/archive.db    reuse (or create, if absent) an archive instead of a temporary one

Also runnable by hand:  python tests/test_evidence_core_perf_5530.py gen DB [EVENTS [MANIFESTS]]  |  measure DB
"""
import hashlib
import json
import os
import subprocess
import sys
import time
from datetime import datetime, timedelta, timezone

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV = "11111111-1111-1111-1111-111111111111"
DAYS = 365
MAX_SECONDS = 600
MAX_RSS_MB = 512

pytestmark = [
    pytest.mark.perf,
    pytest.mark.skipif(os.environ.get("OPA_PERF") != "1", reason="performance test: set OPA_PERF=1 to run"),
]


def _iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S.") + "%03dZ" % (dt.microsecond // 1000)


def generate(path, n_events=1_000_000, manifests=DAYS):
    os.environ["OPA_AUDIT_DB_PATH"] = path
    sys.path.insert(0, ROOT)
    import audit_store
    audit_store.run_migrations()
    conn = audit_store._get_connection()
    curated_types = sorted(audit_store.COMPLIANCE_EVENT_TYPES)
    today = datetime.now(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)
    first_day = today - timedelta(days=DAYS)
    per_day = n_events // DAYS
    extra = n_events - per_day * DAYS
    index = 0
    pending = []  # entries of the days not yet sealed (manifests=1: the whole archive is one first-backfill manifest)
    every = max(DAYS // max(manifests, 1), 1)
    for d in range(DAYS):
        day = first_day + timedelta(days=d)
        count = per_day + (extra if d == DAYS - 1 else 0)
        rows, entries = [], []
        for k in range(count):
            curated = index % 10 != 9
            etype = curated_types[index % len(curated_types)] if curated else "app.misc.synthetic"
            published = _iso(day + timedelta(milliseconds=(k * 86_400_000) // max(count, 1)))
            uuid = "perf-%08d" % index
            raw = json.dumps({
                "uuid": uuid, "eventType": etype, "published": published, "displayMessage": "synthetic " + etype,
                "actor": {"id": "00uActor%d" % (index % 500), "displayName": "Person %d" % (index % 500), "alternateId": "person%d@example.com" % (index % 500)},
                "outcome": {"result": "SUCCESS", "reason": None}, "client": {"ipAddress": "192.0.2.%d" % (index % 250), "geographicalContext": {"city": "Town", "country": "Nowhere"}},
                "target": [{"id": "00uT%d" % (index % 900), "type": "User", "displayName": "Target %d" % (index % 900), "alternateId": "t%d@example.com" % (index % 900)}],
                "authenticationContext": {"externalSessionId": "sess%d" % index},
            }, separators=(",", ":"))
            rows.append((uuid, ENV, etype, published, "00uActor%d" % (index % 500), "Person %d" % (index % 500), "person%d@example.com" % (index % 500),
                         "SUCCESS", 1 if curated else 0, raw, "00uT%d" % (index % 900), "t%d@example.com" % (index % 900), None))
            entries.append((uuid, 1 if curated else 0, hashlib.sha256(raw.encode("utf-8")).hexdigest()))
            index += 1
        conn.executemany(
            "INSERT INTO events (uuid, environment_id, event_type, published, actor_id, actor_display_name, actor_alternate_id, outcome_result, "
            "is_curated, raw_json, resource_id, resource_alternate_id, resource_type_detail) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)", rows)
        pending.extend(entries)
        if (d + 1) % every == 0 or d == DAYS - 1:
            with audit_store._db_lock:  # the rows and their manifest in one transaction (the insert above opened it)
                audit_store._write_manifest_row(conn, ENV, "sync", _iso(day - timedelta(days=every - 1)), _iso(day + timedelta(days=1)), pending)
                conn.commit()
            pending = []
        else:
            conn.commit()
    audit_store._upsert_sync_state(conn, ENV, last_sync_completed_at=_iso(datetime.now(timezone.utc)), last_sync_status="success",
                                   ingestion_scope="all", last_synced_at=_iso(today))
    conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    return {"events": index, "first_day": first_day.date().isoformat(), "last_day": (today - timedelta(days=1)).date().isoformat()}


def measure(path):
    import resource
    os.environ["OPA_AUDIT_DB_PATH"] = path
    sys.path.insert(0, ROOT)
    import audit_store
    import evidence_core as core
    today = datetime.now(timezone.utc).date()
    period = core.parse_period((today - timedelta(days=DAYS)).isoformat(), (today - timedelta(days=1)).isoformat())
    phases = {}
    t_all = time.time()
    with open(os.devnull, "wb") as sink, core.open_snapshot(ENV, period) as snap:
        t = time.time()
        n_lines = 0
        for line in snap.event_lines():
            sink.write(line)
            n_lines += 1
        phases["events_ndjson"] = round(time.time() - t, 1)
        t = time.time()
        csv_rows = 0
        for key in audit_store.COMPLIANCE_REPORTS:
            csv_rows += core.write_report_csv(sink, snap.report_rows(key))
        phases["report_csvs"] = round(time.time() - t, 1)
        t = time.time()
        seal_bytes = 0
        for chunk in snap.iter_seal_chunks():
            sink.write(chunk)
            seal_bytes += len(chunk)
        n_manifests = sum(1 for _ in snap.iter_manifests())
        phases["seals_and_manifests"] = round(time.time() - t, 1)
        t = time.time()
        comp = snap.completeness()
        json.dumps(comp)
        phases["completeness_and_coverage"] = round(time.time() - t, 1)
        counts = snap.report_counts()
    wall = time.time() - t_all
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    rss_mb = rss / (1024 * 1024) if sys.platform == "darwin" else rss / 1024
    assert csv_rows == sum(counts.values()) and n_lines == comp["counts"]["events"]
    return {"events_streamed": n_lines, "report_rows": csv_rows, "manifests": n_manifests, "seal_bytes": seal_bytes,
            "wall_seconds": round(wall, 1), "peak_rss_mb": round(rss_mb, 1), "phases": phases,
            "coverage_pct": comp["coverage"]["coverage_pct"]}


def _run(*args):
    proc = subprocess.run([sys.executable, os.path.abspath(__file__), *args], capture_output=True, text=True, timeout=3000)
    assert proc.returncode == 0, proc.stderr[-2000:]
    return json.loads(proc.stdout.strip().splitlines()[-1])


def test_twelve_months_over_a_large_archive_streams_within_the_limits(tmp_path):
    n = int(os.environ.get("OPA_PERF_EVENTS", "1000000"))
    manifests = int(os.environ.get("OPA_PERF_MANIFESTS", str(DAYS)))   # 1 = the worst case: one manifest holds every event
    db = os.environ.get("OPA_PERF_DB") or str(tmp_path / "perf_archive.db")
    if not os.path.exists(db):
        t = time.time()
        made = _run("gen", db, str(n), str(manifests))
        print("\nperf archive generated:", made, "in %.0fs" % (time.time() - t))
    result = _run("measure", db)
    print("\nperf result:", json.dumps(result))
    assert result["events_streamed"] > 0
    if n >= 1_000_000:
        assert result["wall_seconds"] <= MAX_SECONDS, result
        assert result["peak_rss_mb"] <= MAX_RSS_MB, result


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        print(json.dumps(generate(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 1_000_000, int(sys.argv[4]) if len(sys.argv) > 4 else DAYS)))
    else:
        print(json.dumps(measure(sys.argv[2])))
