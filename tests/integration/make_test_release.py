#!/usr/bin/env python3
"""Builds a TEST-ONLY signed release from a checkout, for tests/integration/updater-vm.sh.

SYNTHETIC: every key here is generated by the script that calls this (`keygen`), lives in a work directory that script
deletes, and is never the project's real release or standby key. The release is signed in the same format the real tool
produces (minisign "ED" signature + manifest.json with a sha256 of every file), so the updater verifies it exactly as it
verifies a real one -- against the TEST key list that was installed as the server's trust list.

    make_test_release.py keygen <dir>
        creates <dir>/primary.key (Ed25519 seed, 0600), <dir>/standby.key (P-256), <dir>/other.key (a stranger's Ed25519
        key) and <dir>/release_keys.json (the test key list: primary + standby)
    make_test_release.py build <checkout> <keys dir> <out dir> <version> [--break MODE] [--sign-with primary|other]
        MODE: none (default) | crash (the application exits at start: a crash loop) | unhealthy (/healthz says degraded)

Needs the `cryptography` package (apt: python3-cryptography) and the checkout's tests/release_helpers.py.
"""

import argparse
import base64
import hashlib
import io
import json
import os
import re
import stat
import sys
import tarfile
from pathlib import Path

CHECKOUT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(CHECKOUT))
sys.path.insert(0, str(CHECKOUT / "tests"))

from cryptography.hazmat.primitives import serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey  # noqa: E402

from release_helpers import TestKey, TestStandby, key_list, sign_release  # noqa: E402

SKIP_DIRS = {".git", ".venv", "node_modules", "__pycache__", ".pytest_cache", "dist", "dist.new", "dist.old", ".claude"}
SKIP_FILES = {"audit_log.jsonl", "access_control.json", "banner_config.json", "environments.json", "update_check.json",
              "release_keys.local.json", ".env", ".deploy.conf", ".deploy.lock", "TestCreds.txt", "ubuntuserver.txt"}


def _save_ed(path, key):
    seed = key.priv.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())
    Path(path).write_text(json.dumps({"seed": base64.b64encode(seed).decode(), "stored_id": key.stored_id.hex()}))
    os.chmod(path, 0o600)


def _load_ed(path):
    d = json.loads(Path(path).read_text())
    k = TestKey.__new__(TestKey)
    k.priv = Ed25519PrivateKey.from_private_bytes(base64.b64decode(d["seed"]))
    k.raw = k.priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    k.stored_id = bytes.fromhex(d["stored_id"])
    k.key_id = k.stored_id[::-1].hex().upper()
    k.status, k.since = "active", "5.46.0"
    return k


def keygen(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    primary, other, standby = TestKey(), TestKey(), TestStandby()
    _save_ed(out / "primary.key", primary)
    _save_ed(out / "other.key", other)
    pem = standby.priv.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    (out / "standby.key").write_bytes(pem)
    os.chmod(out / "standby.key", 0o600)
    (out / "release_keys.json").write_text(json.dumps(key_list([primary, standby]), indent=2) + "\n")
    print(f"test keys written to {out} (primary {primary.key_id}, stranger {other.key_id}); delete the directory when done")


def collect(checkout):
    files = {}
    for base, dirs, names in os.walk(checkout):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS or (d == "dist" and False)]
        for n in names:
            p = Path(base) / n
            rel = p.relative_to(checkout).as_posix()
            if n in SKIP_FILES or n.endswith((".db", ".db-wal", ".db-shm", ".pyc", ".csv")) and n != "folders_template.csv":
                continue
            if p.is_symlink() or not p.is_file():
                continue
            mode = 0o755 if p.stat().st_mode & stat.S_IXUSR else 0o644
            files[rel] = (mode, p.read_bytes())
    files["frontend/dist/index.html"] = (0o644, b"<!doctype html><title>vm test build</title>\n")
    return files


def build(checkout, keys_dir, out_dir, version, mode="none", sign_with="primary"):
    files = collect(Path(checkout))
    engine = files["create_secret_folders.py"][1].decode()
    files["create_secret_folders.py"] = (0o644, re.sub(r'^SCRIPT_VERSION = "[^"]+"', f'SCRIPT_VERSION = "{version}"', engine, flags=re.M).encode())
    files["server/release_keys.json"] = (0o644, (Path(keys_dir) / "release_keys.json").read_bytes())
    serve = files["server/serve.py"][1].decode()
    if mode == "crash":
        # must sit BEFORE the `__main__` call: appended after it, the server would run forever and the line never be reached
        tail = 'if __name__ == "__main__":\n    main()'
        assert tail in serve
        serve = serve.replace(tail, 'if __name__ == "__main__":\n    import sys as _s\n    _s.exit("test release: deliberately refuses to start")')
    elif mode == "unhealthy":
        serve = serve.replace('status = "ok" if all(v == "ok" for v in checks.values()) else "degraded"',
                              'status = "degraded"  # test release: deliberately unhealthy')
        assert "deliberately unhealthy" in serve
    files["server/serve.py"] = (0o644, serve.encode())
    schema = max(int(n) for n in re.findall(r"^\s*(\d+):\s*_migration_", files["audit_store.py"][1].decode(), re.M))
    manifest = {"schema": 1, "version": version, "commit": "0" * 40, "built_at": "2026-01-15T10:00:00Z", "min_upgrade_from": "0.0.0",
                "downtime_estimate_seconds": 45, "migrations": [], "expected_schema_version": schema, "nginx_template_changed": True,
                "migration_time_estimate_seconds": 30, "changelog_excerpt": "vm test build",
                "files": {n: hashlib.sha256(d).hexdigest() for n, (_m, d) in sorted(files.items())}}
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    tar_path = out / f"ocw-{version}.tar.gz"
    import gzip
    with open(tar_path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, filename="") as gz, tarfile.open(fileobj=gz, mode="w") as tar:
        for name, (m, data) in sorted({**files, "manifest.json": (0o644, (json.dumps(manifest, indent=2) + "\n").encode())}.items()):
            info = tarfile.TarInfo(name)
            info.size, info.mode, info.mtime = len(data), m, 1
            tar.addfile(info, io.BytesIO(data))
    key = _load_ed(Path(keys_dir) / ("primary.key" if sign_with == "primary" else "other.key"))
    sign_release(tar_path, key, version, timestamp="2026-01-15T10:00:00Z")
    print(f"built {tar_path} ({len(files)} files, version {version}, break={mode}, signed by {sign_with})")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen")
    k.add_argument("dir")
    b = sub.add_parser("build")
    b.add_argument("checkout")
    b.add_argument("keys")
    b.add_argument("out")
    b.add_argument("version")
    b.add_argument("--break", dest="mode", default="none", choices=["none", "crash", "unhealthy"])
    b.add_argument("--sign-with", default="primary", choices=["primary", "other"])
    a = ap.parse_args()
    if a.cmd == "keygen":
        keygen(a.dir)
    else:
        build(a.checkout, a.keys, a.out, a.version, a.mode, a.sign_with)


if __name__ == "__main__":
    main()
